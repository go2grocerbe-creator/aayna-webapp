#!/usr/bin/env python3
"""Regenerate backend/static_gallery_data.py from frontend/src/data/productGallery.json.

The backend runs as a Vercel Python function that bundles only backend/*.py, so it cannot read
the frontend JSON at runtime. This writes the same reviewed photo order (SKU -> image URLs) as a
Python module. tests_import/test_gallery.py fails if the two ever drift apart.
    python scripts/assets/build_static_gallery_py.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
src = json.loads((ROOT / "frontend/src/data/productGallery.json").read_text(encoding="utf-8"))["products"]
data = {sku: [{"src": i["src"], "srcSet": i.get("srcSet", "")} for i in v["images"]] for sku, v in sorted(src.items())}
out = ('"""GENERATED by scripts/assets/build_static_gallery_py.py from frontend/src/data/productGallery.json.\n'
       'Do not edit by hand. SKU -> reviewed static product photos (first = default cover)."""\n'
       f"STATIC_GALLERY = {json.dumps(data, indent=1, ensure_ascii=False)}\n")
(ROOT / "backend/static_gallery_data.py").write_text(out, encoding="utf-8")
print(f"{len(data)} SKUs, {sum(len(v) for v in data.values())} photos")
